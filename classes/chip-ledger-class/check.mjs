import { assert, load } from './runtime.mjs';
const m = await load('server/index.ts');
const initial = m.openLedger([{ id: 'a', seat: 0 }, { id: 'b', seat: 1 }], { startingStack: 101 });
const snapshot = structuredClone(initial);
let state = m.commit(initial, 'a', 51).ledger;
state = m.commit(state, 'b', 51).ledger;
assert.deepEqual(m.audit(state), { inPlay: 202, issued: 202, balanced: true });
const pots = m.buildPots(state);
assert.deepEqual(pots, [{ amount: 102, eligible: ['a', 'b'] }]);
state = m.settle(state, pots.map(p => m.awardPot(state, p, ['b'], 0)));
assert.equal(m.balance(state, 'a'), 50);
assert.equal(m.balance(state, 'b'), 152);
assert.equal(m.audit(state).balanced, true);
assert.deepEqual(initial, snapshot);
assert.deepEqual(m.splitAmount(5, ['a', 'b']), [{ id: 'a', amount: 3 }, { id: 'b', amount: 2 }]);
assert.throws(() => m.commit(initial, 'a', -1));
assert.throws(() => m.settle(initial, [{ amount: 1, eligible: ['a'], winners: [{ id: 'a', amount: 1 }] }]));
const encoded = m.exportLedger(state);
assert.deepEqual(m.importLedger(encoded), state);
assert.throws(() => m.importLedger(encoded.replace('152', '153')));
let side = m.openLedger([{ id: 'a', seat: 0 }, { id: 'b', seat: 1 }, { id: 'c', seat: 2 }], { startingStack: 100 });
for (const [id, amount] of [['a', 10], ['b', 20], ['c', 20]]) side = m.commit(side, id, amount).ledger;
side = m.fold(side, 'c');
const split = m.buildPots(side);
assert.deepEqual(split, [{ amount: 30, eligible: ['a', 'b'] }, { amount: 20, eligible: ['b'] }]);
const paid = m.settle(side, split.map(pot => m.awardPot(side, pot, ['b'], 0)));
assert.equal(m.balance(paid, 'b'), 130);
assert.equal(m.audit(paid).inPlay, 300);
assert.equal(m.audit(paid).balanced, true);
